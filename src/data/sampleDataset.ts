export function convertDatasetToCSV(records: PatientRecord[]): string {
  const headers = [
    "patient_id",
    "persona",
    "age_group",
    "service_line",
    "visit_type",
    "satisfaction_score",
    "communication_rating",
    "follow_up_compliance",
    "complaint_severity",
    "patient_portal_usage",
    "readmission_risk",
    "ai_risk_flag",
    "ai_risk_details",
    "comment",
    "date"
  ];

  const escapeCSV = (val: string | number | boolean | undefined) => {
    if (val === undefined || val === null) return '""';
    const str = String(val).replace(/"/g, '""');
    return `"${str}"`;
  };

  const rows = records.map(r => [
    escapeCSV(r.patient_id),
    escapeCSV(r.persona),
    escapeCSV(r.age_group),
    escapeCSV(r.service_line),
    escapeCSV(r.visit_type),
    r.satisfaction_score,
    r.communication_rating,
    r.follow_up_compliance,
    escapeCSV(r.complaint_severity),
    escapeCSV(r.patient_portal_usage),
    escapeCSV(r.readmission_risk),
    escapeCSV(r.ai_risk_flag),
    escapeCSV(r.ai_risk_details || ""),
    escapeCSV(r.comment),
    escapeCSV(r.date)
  ].join(","));

  return [headers.join(","), ...rows].join("\n");
}
